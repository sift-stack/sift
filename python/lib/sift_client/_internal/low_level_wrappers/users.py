from __future__ import annotations

import logging
from typing import TYPE_CHECKING, Any, cast

from sift.users.v2.users_pb2 import (
    GetUserRequest,
    GetUserResponse,
    ListActiveUsersRequest,
    ListActiveUsersResponse,
    ListUsersRequest,
    ListUsersResponse,
)
from sift.users.v2.users_pb2_grpc import UserServiceStub

from sift_client._internal.low_level_wrappers.base import LowLevelClientBase
from sift_client.sift_types.user import User
from sift_client.transport import WithGrpcClient

if TYPE_CHECKING:
    from sift_client.transport.grpc_transport import GrpcClient

logger = logging.getLogger(__name__)


class UsersLowLevelClient(LowLevelClientBase, WithGrpcClient):
    """Low-level client for the UserService.

    A thin wrapper around the autogenerated bindings; each method maps to a single RPC.
    """

    def __init__(self, grpc_client: GrpcClient):
        super().__init__(grpc_client)

    @property
    def _stub(self) -> UserServiceStub:
        return self._grpc_client.get_stub(UserServiceStub)

    async def get_user(self, user_id: str) -> User:
        response = cast(
            "GetUserResponse",
            await self._stub.GetUser(GetUserRequest(user_id=user_id)),
        )
        return User._from_proto(response.user)

    async def list_active_users(
        self,
        *,
        page_size: int | None = None,
        page_token: str | None = None,
        query_filter: str | None = None,
        order_by: str | None = None,
        organization_id: str | None = None,
    ) -> tuple[list[User], str]:
        request_kwargs: dict[str, Any] = {}
        if page_size:
            request_kwargs["page_size"] = page_size
        if page_token:
            request_kwargs["page_token"] = page_token
        if query_filter:
            request_kwargs["filter"] = query_filter
        if order_by:
            request_kwargs["order_by"] = order_by
        if organization_id:
            request_kwargs["organization_id"] = organization_id

        response = cast(
            "ListActiveUsersResponse",
            await self._stub.ListActiveUsers(ListActiveUsersRequest(**request_kwargs)),
        )
        users = [User._from_proto(u) for u in response.users]
        return users, response.next_page_token

    async def list_all_active_users(
        self,
        *,
        query_filter: str | None = None,
        order_by: str | None = None,
        organization_id: str | None = None,
        page_size: int | None = None,
        max_results: int | None = None,
    ) -> list[User]:
        return await self._handle_pagination(
            self.list_active_users,
            kwargs={"query_filter": query_filter, "organization_id": organization_id},
            page_size=page_size,
            order_by=order_by,
            max_results=max_results,
        )

    async def list_users(
        self,
        *,
        page_size: int | None = None,
        page_token: str | None = None,
        query_filter: str | None = None,
        order_by: str | None = None,
    ) -> tuple[list[User], str]:
        request_kwargs: dict[str, Any] = {}
        if page_size:
            request_kwargs["page_size"] = page_size
        if page_token:
            request_kwargs["page_token"] = page_token
        if query_filter:
            request_kwargs["filter"] = query_filter
        if order_by:
            request_kwargs["order_by"] = order_by

        response = cast(
            "ListUsersResponse",
            await self._stub.ListUsers(ListUsersRequest(**request_kwargs)),
        )
        users = [User._from_proto(u) for u in response.users]
        return users, response.next_page_token

    async def list_all_users(
        self,
        *,
        query_filter: str | None = None,
        order_by: str | None = None,
        page_size: int | None = None,
        max_results: int | None = None,
    ) -> list[User]:
        return await self._handle_pagination(
            self.list_users,
            kwargs={"query_filter": query_filter},
            page_size=page_size,
            order_by=order_by,
            max_results=max_results,
        )
