logger = logging.getLogger(__name__)


class UserDefinedFunctionsLowLevelClient(LowLevelClientBase, WithGrpcClient):
    """Low-level client for the UserDefinedFunctionsAPI.

    A thin wrapper around the autogenerated bindings for the UserDefinedFunctionService.
    """

    def __init__(self, grpc_client: GrpcClient):
        """Initialize the UserDefinedFunctionsLowLevelClient.

        Args:
            grpc_client: The gRPC client to use for making API calls.
        """
        super().__init__(grpc_client)

    async def get_function(self, function_id: str) -> UserDefinedFunction:
        """Get a function by ID.

        Args:
            function_id: The function ID to get.

        Returns:
            The UserDefinedFunction.
        """
        request = GetUserDefinedFunctionRequest(user_defined_function_id=function_id)
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).GetUserDefinedFunction(request)
        return UserDefinedFunction._from_proto(
            cast("GetUserDefinedFunctionResponse", response).user_defined_function
        )

    async def get_version(self, version_id: str) -> UserDefinedFunctionVersion:
        """Get one version of a function.

        Args:
            version_id: The version ID to get.

        Returns:
            The UserDefinedFunctionVersion.
        """
        request = GetUserDefinedFunctionVersionRequest(user_defined_function_version_id=version_id)
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).GetUserDefinedFunctionVersion(request)
        return UserDefinedFunctionVersion._from_proto(
            cast("GetUserDefinedFunctionVersionResponse", response).user_defined_function
        )

    async def get_versions(self, version_ids: list[str]) -> list[UserDefinedFunctionVersion]:
        """Get many versions in one call.

        Args:
            version_ids: The version IDs to get.

        Returns:
            The UserDefinedFunctionVersions.
        """
        if not version_ids:
            return []
        request = GetUserDefinedFunctionVersionsRequest(
            user_defined_function_version_ids=version_ids
        )
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).GetUserDefinedFunctionVersions(request)
        response = cast("GetUserDefinedFunctionVersionsResponse", response)
        return [UserDefinedFunctionVersion._from_proto(f) for f in response.user_defined_functions]

    async def list_functions(
        self,
        *,
        page_size: int | None = DEFAULT_PAGE_SIZE,
        page_token: str | None = None,
        query_filter: str | None = None,
        order_by: str | None = None,
    ) -> tuple[list[UserDefinedFunction], str]:
        """List one page of functions.

        Args:
            page_size: The maximum number of functions to return.
            page_token: A page token for pagination.
            query_filter: A CEL filter string.
            order_by: How to order the retrieved functions.

        Returns:
            A tuple of (functions, next_page_token).
        """
        request_kwargs: dict[str, Any] = {}
        if page_size is not None:
            request_kwargs["page_size"] = page_size
        if page_token is not None:
            request_kwargs["page_token"] = page_token
        if query_filter is not None:
            request_kwargs["filter"] = query_filter
        if order_by is not None:
            request_kwargs["order_by"] = order_by

        request = ListUserDefinedFunctionsRequest(**request_kwargs)
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).ListUserDefinedFunctions(request)
        response = cast("ListUserDefinedFunctionsResponse", response)

        functions = [UserDefinedFunction._from_proto(f) for f in response.user_defined_functions]
        return functions, response.next_page_token

    async def list_all_functions(
        self,
        *,
        query_filter: str | None = None,
        order_by: str | None = None,
        page_size: int | None = DEFAULT_PAGE_SIZE,
        max_results: int | None = None,
    ) -> list[UserDefinedFunction]:
        """List every matching function.

        Args:
            query_filter: A CEL filter string.
            order_by: How to order the retrieved functions.
            page_size: The number of results to fetch per request.
            max_results: Maximum number of results to return.

        Returns:
            A list of all matching functions.
        """
        return await self._handle_pagination(
            self.list_functions,
            kwargs={"query_filter": query_filter},
            order_by=order_by,
            max_results=max_results,
            page_size=page_size,
        )

    async def list_versions(
        self,
        *,
        function_id: str | None = None,
        name: str | None = None,
        page_size: int | None = DEFAULT_PAGE_SIZE,
        page_token: str | None = None,
        query_filter: str | None = None,
        order_by: str | None = None,
    ) -> tuple[list[UserDefinedFunctionVersion], str]:
        """List one page of versions for a function.

        Args:
            function_id: The function whose versions to list.
            name: The function name, as an alternative to the ID.
            page_size: The maximum number of versions to return.
            page_token: A page token for pagination.
            query_filter: A CEL filter string.
            order_by: How to order the retrieved versions.

        Returns:
            A tuple of (versions, next_page_token).
        """
        request_kwargs: dict[str, Any] = {}
        if function_id is not None:
            request_kwargs["user_defined_function_id"] = function_id
        if name is not None:
            request_kwargs["name"] = name
        if page_size is not None:
            request_kwargs["page_size"] = page_size
        if page_token is not None:
            request_kwargs["page_token"] = page_token
        if query_filter is not None:
            request_kwargs["filter"] = query_filter
        if order_by is not None:
            request_kwargs["order_by"] = order_by

        request = ListUserDefinedFunctionVersionsRequest(**request_kwargs)
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).ListUserDefinedFunctionVersions(request)
        response = cast("ListUserDefinedFunctionVersionsResponse", response)

        versions = [
            UserDefinedFunctionVersion._from_proto(f) for f in response.user_defined_functions
        ]
        return versions, response.next_page_token

    async def list_all_versions(
        self,
        *,
        function_id: str | None = None,
        name: str | None = None,
        query_filter: str | None = None,
        order_by: str | None = None,
        page_size: int | None = DEFAULT_PAGE_SIZE,
        max_results: int | None = None,
    ) -> list[UserDefinedFunctionVersion]:
        """List every matching version.

        Args:
            function_id: The function whose versions to list.
            name: The function name, as an alternative to the ID.
            query_filter: A CEL filter string.
            order_by: How to order the retrieved versions.
            page_size: The number of results to fetch per request.
            max_results: Maximum number of results to return.

        Returns:
            A list of all matching versions.
        """
        return await self._handle_pagination(
            self.list_versions,
            kwargs={"function_id": function_id, "name": name, "query_filter": query_filter},
            order_by=order_by,
            max_results=max_results,
            page_size=page_size,
        )

    async def create_function(self, *, create: UserDefinedFunctionCreate) -> UserDefinedFunction:
        """Create a function.

        Args:
            create: The function definition.

        Returns:
            The created UserDefinedFunction.
        """
        request_proto = create.to_proto()
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).CreateUserDefinedFunction(request_proto)
        return UserDefinedFunction._from_proto(
            cast("CreateUserDefinedFunctionResponse", response).user_defined_function
        )

    async def update_function(
        self, update: UserDefinedFunctionUpdate, change_notes: str | None = None
    ) -> UserDefinedFunction:
        """Update select fields of a function.

        Args:
            update: The updates to apply. Its `resource_id` must be set.
            change_notes: The note to attach to the new version.

        Returns:
            The updated UserDefinedFunction.
        """
        grpc_function, update_mask = update.to_proto_with_mask()
        if change_notes is not None:
            grpc_function.user_notes = change_notes
        request = UpdateUserDefinedFunctionRequest(
            user_defined_function=grpc_function, update_mask=update_mask
        )
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).UpdateUserDefinedFunction(request)
        return UserDefinedFunction._from_proto(
            cast("UpdateUserDefinedFunctionResponse", response).user_defined_function
        )

    async def validate_function(
        self, *, expression: str, function_inputs: list[FunctionInput]
    ) -> UserDefinedFunctionValidation:
        """Check an expression without saving it.

        Args:
            expression: The expression to check.
            function_inputs: The inputs the expression refers to.

        Returns:
            Whether the expression compiles, and its output type or error.
        """
        request = ValidateUserDefinedFunctionRequest(
            expression=expression,
            function_inputs=[
                _function_input_to_proto(**i.model_dump()) for i in function_inputs or []
            ],
        )
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).ValidateUserDefinedFunction(request)
        response = cast("ValidateUserDefinedFunctionResponse", response)

        if response.WhichOneof("result") == "error":
            return UserDefinedFunctionValidation(is_valid=False, error=response.error.error_message)
        output_type = response.success.user_defined_function.function_output_type
        return UserDefinedFunctionValidation(
            is_valid=True,
            output_type=FunctionDataType(output_type) if output_type else None,
        )

    async def get_dependents(
        self,
        *,
        function_id: str | None = None,
        name: str | None = None,
        version_id: str | None = None,
    ) -> FunctionUsage:
        """Get what depends on a function.

        Exactly one identifier must be provided.

        Args:
            function_id: The function ID.
            name: The function name.
            version_id: A specific version ID.

        Returns:
            The functions, calculated channels, and rules that use it.

        Raises:
            ValueError: If not exactly one identifier is provided.
        """
        given = [v for v in (function_id, name, version_id) if v is not None]
        if len(given) != 1:
            raise ValueError("Exactly one of function_id, name, or version_id must be provided")

        request_kwargs: dict[str, Any] = {}
        if function_id is not None:
            request_kwargs["user_defined_function_id"] = function_id
        elif name is not None:
            request_kwargs["user_defined_function_name"] = name
        else:
            request_kwargs["user_defined_function_version_id"] = version_id

        request = GetUserDefinedFunctionDependentsRequest(**request_kwargs)
        response = await self._grpc_client.get_stub(
            UserDefinedFunctionServiceStub
        ).GetUserDefinedFunctionDependents(request)
        response = cast("GetUserDefinedFunctionDependentsResponse", response)

        return FunctionUsage(
            functions=[UserDefinedFunction._from_proto(f) for f in response.user_defined_functions],
            calculated_channels=[
                CalculatedChannel._from_proto(c) for c in response.calculated_channels
            ],
            rules=[Rule._from_proto(r) for r in response.rules],
        )
